export function getCarById(id: string): Car | undefined {
  return CARS.find((car) => car.id === id);
}

export function getMakes(): string[] {
  return [...new Set(CARS.map((car) => car.make))].sort();
}

export function getModels(make?: string): string[] {
  const source = make ? CARS.filter((car) => car.make === make) : CARS;
  return [...new Set(source.map((car) => car.model))].sort();
}

export function relatedCars(car: Car, limit = 4): Car[] {
  return CARS.filter(
    (item) =>
      item.id !== car.id &&
      (item.make === car.make || item.bodyType === car.bodyType),
  ).slice(0, limit);
}
